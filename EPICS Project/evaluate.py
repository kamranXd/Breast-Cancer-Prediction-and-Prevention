"""Evaluate the trained model on a labelled test set and refresh model_metrics.json.

The repository only ships the training notebook's metrics, which do not include
ROC-AUC. Point this script at a labelled test set to measure the model properly:

    python evaluate.py --cancer-dir data/test/cancer \
                       --non-cancer-dir data/test/non_cancer

Every image directly inside each directory is scored (non-recursive).
"""
import argparse
import json
import os

import numpy as np


def collect_files(directory):
    files = []
    for name in sorted(os.listdir(directory)):
        path = os.path.join(directory, name)
        if os.path.isfile(path) and not name.startswith('.'):
            files.append(path)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cancer-dir', required=True,
                        help='directory of cancer (positive) images')
    parser.add_argument('--non-cancer-dir', required=True,
                        help='directory of non-cancer (negative) images')
    parser.add_argument('--model-path', default=os.getenv('MODEL_PATH', 'imagenet_model.h5'),
                        help='path to the saved weights (default: %(default)s)')
    parser.add_argument('--output', default='model_metrics.json',
                        help='where to write the metrics (default: %(default)s)')
    parser.add_argument('--threshold', type=float, default=0.5,
                        help='decision threshold for the binary metrics (default: %(default)s)')
    parser.add_argument('--batch-size', type=int, default=16)
    args = parser.parse_args()

    # Imported late so --help stays fast and TF noise does not pollute it.
    from sklearn.metrics import (confusion_matrix, precision_recall_fscore_support,
                                 roc_auc_score)

    import backend

    cancer = collect_files(args.cancer_dir)
    non_cancer = collect_files(args.non_cancer_dir)
    if not cancer or not non_cancer:
        raise SystemExit('Both directories must contain at least one image.')

    paths = non_cancer + cancer
    labels = np.array([0] * len(non_cancer) + [1] * len(cancer))
    print(f'Scoring {len(paths)} images ({len(cancer)} cancer, {len(non_cancer)} non-cancer)')

    if backend.MODEL_PATH != args.model_path:
        backend.MODEL_PATH = args.model_path
    model = backend.get_model()

    scores = []
    for start in range(0, len(paths), args.batch_size):
        batch = paths[start:start + args.batch_size]
        batch_x = np.concatenate([backend.preprocess_image(p) for p in batch], axis=0)
        scores.extend(model.predict(batch_x, verbose=0).ravel().tolist())
        print(f'  {min(start + args.batch_size, len(paths))}/{len(paths)}', end='\r')
    print()

    scores = np.array(scores, dtype=float)
    predicted = (scores >= args.threshold).astype(int)

    precision, recall, f1, support = precision_recall_fscore_support(
        labels, predicted, labels=[0, 1], zero_division=0)
    accuracy = float((predicted == labels).mean())
    try:
        roc_auc = float(roc_auc_score(labels, scores))
    except ValueError:
        roc_auc = None
    cm = confusion_matrix(labels, predicted, labels=[0, 1]).tolist()

    metrics = {
        'model': 'EfficientNetB3 (ImageNet weights, frozen) + GlobalAveragePooling2D + Dropout(0.5) + Dense(1, sigmoid)',
        'dataset': os.path.basename(os.path.dirname(os.path.abspath(args.cancer_dir))) or 'local test set',
        'evaluation_split': 'external test set supplied to evaluate.py',
        'validation_samples': int(len(paths)),
        'threshold': args.threshold,
        'positive_class': 'Cancer',
        'accuracy': round(accuracy, 4),
        'precision_cancer': round(float(precision[1]), 4),
        'recall_cancer': round(float(recall[1]), 4),
        'f1_cancer': round(float(f1[1]), 4),
        'support_cancer': int(support[1]),
        'precision_non_cancer': round(float(precision[0]), 4),
        'recall_non_cancer': round(float(recall[0]), 4),
        'f1_non_cancer': round(float(f1[0]), 4),
        'support_non_cancer': int(support[0]),
        'macro_f1': round(float(f1.mean()), 4),
        'roc_auc': round(roc_auc, 4) if roc_auc is not None else None,
        'confusion_matrix': {'labels': ['non_cancer', 'cancer'], 'matrix': cm},
        'source': 'evaluate.py',
        'notes': 'Regenerated by evaluate.py against a labelled test set.',
    }

    with open(args.output, 'w', encoding='utf-8') as handle:
        json.dump(metrics, handle, indent=2)
        handle.write('\n')

    print(json.dumps({k: v for k, v in metrics.items()
                      if k not in ('notes', 'model')}, indent=2))
    print(f'\nWrote {args.output}')


if __name__ == '__main__':
    main()
